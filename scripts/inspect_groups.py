"""Catalogue every signal stored for one shot (all groups, not only summary) from the store's own metadata.

Writes results/data_catalogue/shot_<id>.md. This is the "inspect the real data first" step before any new
group becomes a feature (ROADMAP D1/D2).
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import requests

from src import config

GEOMETRY_WORDS = ("_r", "_z", "_phi", "geometry", "length", "height", "width", "shapeAngle", "coordinate")


def root_metadata(shot_id):
    """The root zarr.json of a shot's store as a dict (it lists every array in 'consolidated_metadata')."""
    url = config.SHOT_ZARR_URL.format(shot_id=shot_id) + "/zarr.json"
    if url.startswith("http"):
        response = requests.get(url, timeout=60)
        response.raise_for_status()
        return response.json()
    with open(url) as f:
        return json.load(f)


def catalogue(meta, include_geometry=False):
    """One row per array: group, name, shape, units, description, original UDA name, dimension names."""
    rows = []
    for key, node in sorted(meta.get("consolidated_metadata", {}).get("metadata", {}).items()):
        if node.get("node_type") != "array" or "/" not in key:
            continue
        group, name = key.split("/", 1)
        if not include_geometry and any(word in name for word in GEOMETRY_WORDS):
            continue
        attrs = node.get("attributes", {})
        rows.append({"group": group, "name": name, "shape": node.get("shape"), "units": attrs.get("units") or "",
                     "description": (attrs.get("description") or "")[:80], "uda_name": attrs.get("uda_name") or "",
                     "dims": node.get("dimension_names") or []})
    return rows


def markdown(shot_id, rows):
    """Markdown table of the catalogue, grouped by group."""
    lines = [f"# Signals stored for shot {shot_id}", "",
             "Generated by `scripts/inspect_groups.py` from the store's consolidated metadata (no values read). "
             "Geometry arrays are left out unless `--geometry` is given.", ""]
    for group in sorted({r["group"] for r in rows}):
        lines += [f"## {group}", "", "| name | shape | units | description | UDA name | dims |", "|---|---|---|---|---|---|"]
        for r in rows:
            if r["group"] == group:
                lines.append(f"| {r['name']} | {r['shape']} | {r['units']} | {r['description']} | {r['uda_name']} | "
                             f"{', '.join(r['dims'])} |")
        lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--shot", type=int, default=config.REFERENCE_SHOT)
    parser.add_argument("--geometry", action="store_true", help="include coil and probe geometry arrays")
    args = parser.parse_args()
    rows = catalogue(root_metadata(args.shot), args.geometry)
    out_dir = os.path.join(config.RESULTS_DIR, "data_catalogue")
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, f"shot_{args.shot}.md")
    with open(path, "w") as f:
        f.write(markdown(args.shot, rows))
    print(f"{len(rows)} arrays in {len({r['group'] for r in rows})} groups -> {path}")


if __name__ == "__main__":
    main()
